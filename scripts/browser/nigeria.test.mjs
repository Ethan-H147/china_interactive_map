import assert from 'node:assert/strict';
import {searchAndSelect} from './countries.test.mjs';
import {load} from '../geo-index.mjs';
const first=load('dist/data/europe/nigeria/catalogue.bin').records.filter(r=>r.level===1);
export default [1280,390].map(width=>({name:'Nigeria states, local areas, FCT councils, flag, saved view and quiz '+width,options:{width,height:900,mobile:width===390},async run(p,base){
 await p.open(base,'#nigeria');
 assert.equal(await p.evaluate('AtlasEntry.current'),'nigeria');
 assert.equal(await p.evaluate(`document.querySelectorAll('#ng-province option[value]:not([value=""])').length`),37);
 assert(await p.evaluate('map.queryRenderedFeatures({layers:["nigeria-first-fill"]}).length>0'));
 assert(!await p.evaluate('!!map.getSource("nigeria-second")'),'Local geometry loads on demand');
 await searchAndSelect(p,'Lagos','Lagos','State');assert.equal(await p.evaluate('currentAtlas().getSelection()'),'NG025');
 await p.waitFor('map.queryRenderedFeatures({layers:["nigeria-second-fill"]}).length>0');
 assert((await p.evaluate('document.getElementById("ng-statistics").parentElement.textContent')).includes('Mapped land area'));
 await searchAndSelect(p,'Ikeja','Ikeja','Local government area');assert.equal(await p.evaluate('currentAtlas().getSelection()'),'NG025011');
 assert(await p.evaluate('map.queryRenderedFeatures({layers:["nigeria-second-selected"]}).length>0'));
 const hash=await p.evaluate('AtlasView.hashFor(captureView())');await p.open(base,hash);assert.equal(await p.evaluate('currentAtlas().getSelection()'),'NG025011');
 await searchAndSelect(p,'FCT','Federal Capital Territory','Federal capital territory');assert.equal(await p.evaluate('currentAtlas().getSelection()'),'NG015');
 await searchAndSelect(p,'Abuja Municipal','Abuja Municipal','Area council');assert.equal(await p.evaluate('currentAtlas().getSelection()'),'NG015002');
 const flag='#nigeria-sidebar .division-flags img[src="vendor/flag-ng.svg"]';
 await p.tap(flag);await p.waitFor('document.getElementById("flag-viewer").open');
 assert.equal(await p.evaluate('document.getElementById("flag-viewer-image").getAttribute("src")'),'vendor/flag-ng.svg');await p.key('Escape');
 assert(await p.evaluate('document.documentElement.scrollWidth<=innerWidth'));
 await p.screenshot('nigeria-selected-'+width);
 await p.evaluate('currentAtlas().home()');await p.settle();await p.tap('#ng-tab-quiz');
 assert((await p.evaluate('document.querySelector("#ng-quiz-panel [data-q=count]").textContent')).startsWith('37 '));
 await p.tap('#ng-quiz-panel [data-q=start]');await p.settle();assert(await p.evaluate('currentAtlas().quiz.active'));
 const question=await p.evaluate('document.querySelector("#ng-quiz-panel [data-q=question]").textContent'),answer=first.find(r=>r.en===question);assert(answer);
 await p.evaluate('void map.jumpTo({center:'+JSON.stringify(answer.center)+',zoom:7})');await p.settle();
 await p.tap(await p.evaluate('(()=>{const p=map.project('+JSON.stringify(answer.center)+'),r=map.getCanvas().getBoundingClientRect();return[r.x+p.x,r.y+p.y]})()'));
 await p.waitFor('document.querySelector("#ng-quiz-panel [data-q=feedback]").textContent==="Correct"');
 await p.tap('#ng-quiz-panel [data-q=end]');await p.settle();
 assert(await p.evaluate('mapScene.assertOrder()'));
}}));
