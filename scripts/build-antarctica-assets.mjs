import fs from 'node:fs';
import {gzipSync,gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {preserveAntarctica} from './antarctic-claims.mjs';
import {encodeGeo} from '../dist/geo-pack.mjs';
import {compactSources} from './build-compact.mjs';
import {build as buildCoverage} from './build-context-coverage.mjs';
await preserveAntarctica();
const present=compactSources.filter(f=>fs.existsSync('dist/data/'+f)),empty=[];
for(const file of present){
 const text=gunzipSync(fs.readFileSync('dist/data/'+file)).toString(),data=JSON.parse(text),hash=createHash('sha256').update(text).digest('hex'),target='dist/data/compact/'+file;
 if(data.type==='FeatureCollection'&&!data.features.length)empty.push(file);
 fs.mkdirSync(target.slice(0,target.lastIndexOf('/')),{recursive:true});fs.writeFileSync(target,gzipSync(encodeGeo(data,{source:hash}),{level:9}));
}
fs.writeFileSync('dist/compact-files.mjs','// Generated by scripts/build-compact.mjs: data files published with a compact copy under data/compact/.\nexport const compactFiles='+JSON.stringify(present)+';\nexport const emptyGeometryFiles='+JSON.stringify(empty)+';\n');
await buildCoverage();
await import('./build-border-previews.mjs');
await import('./build-globe-overview.mjs');
console.log('Antarctica and claimant-only contexts refreshed; compact and globe assets current.');
