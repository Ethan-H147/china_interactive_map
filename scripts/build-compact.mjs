import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync,gunzipSync} from 'node:zlib';
import {pathToFileURL} from 'node:url';

// Compact copies (dist/geo-pack.mjs) of the gzip GeoJSON outlines visitors download at
// startup and right after it. The gzip JSON files stay the build inputs and outputs every
// script reads; the page requests the copy under dist/data/compact/ instead, through
// compactUrl(). Each copy records the SHA-256 of its source so test:compact catches a stale one.
export const compactSources=[
 'world-land.bin','china-context.bin','china-neighbours.bin','shared-context-borders.bin','atlas-frontiers.bin','flight-context.bin',
 'korea-context.bin','mongolia-context.bin','japan-context.bin',
 'archipelago/philippines-context.bin','archipelago/indonesia-context.bin',
 'southeast-asia/malaysia-context.bin','southeast-asia/singapore-context.bin',
 'russia/context.bin','russia/international.bin',
 ...['south-africa','botswana','namibia','eswatini','lesotho'].flatMap(c=>[`southern-africa/${c}/context.bin`,`southern-africa/${c}/international.bin`]),
 ...['united-kingdom','spain','france','italy'].flatMap(c=>['context','neighbours','international'].map(f=>`europe/${c}/${f}.bin`))
];

if(import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 const {encodeGeo}=await import('../dist/geo-pack.mjs');
 const present=compactSources.filter(f=>fs.existsSync('dist/data/'+f));
 fs.rmSync('dist/data/compact',{recursive:true,force:true});
 let before=0,after=0;
 for(const file of present){
  const source=fs.readFileSync('dist/data/'+file),text=gunzipSync(source).toString('utf8');
  const packed=gzipSync(encodeGeo(JSON.parse(text),{source:createHash('sha256').update(text).digest('hex')}),{level:9});
  fs.mkdirSync(path.dirname('dist/data/compact/'+file),{recursive:true});fs.writeFileSync('dist/data/compact/'+file,packed);
  before+=source.length;after+=packed.length;
  console.log(file.padEnd(44),(source.length/1024).toFixed(0).padStart(6),'KB ->',(packed.length/1024).toFixed(0).padStart(5),'KB');
 }
 fs.writeFileSync('dist/compact-files.mjs',`// Generated by scripts/build-compact.mjs: data files published with a compact copy under data/compact/.\nexport const compactFiles=${JSON.stringify(present)};\n`);
 console.log(`Compact copies: ${present.length} files, ${(before/1048576).toFixed(2)} MB -> ${(after/1048576).toFixed(2)} MB.`);
}
