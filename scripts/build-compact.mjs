import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync,gunzipSync} from 'node:zlib';
import {pathToFileURL} from 'node:url';
import '../dist/countries.js';

// Compact copies (dist/geo-pack.mjs) of the gzip GeoJSON outlines visitors download at
// startup and right after it. The gzip JSON files stay the build inputs and outputs every
// script reads; the page requests the copy under dist/data/compact/ instead, through
// compactUrl(). Each copy records the SHA-256 of its source so test:compact catches a stale one.
export const compactSources=[
 ...globalThis.AtlasCountries.ids.flatMap(id=>globalThis.AtlasCountries.countries[id].contextFile||[]),
 'world-land.bin','world-country-outlines.bin','china-context.bin','china-neighbours.bin','shared-context-borders.bin','atlas-frontiers.bin','flight-context.bin',
 'korea-context.bin','mongolia-context.bin','japan-context.bin',
 'archipelago/philippines-context.bin','archipelago/indonesia-context.bin',
 'southeast-asia/malaysia-context.bin','southeast-asia/singapore-context.bin',
 'russia/context.bin','russia/international.bin',
 'antarctica/coast.bin',
 ...['south-africa','botswana','namibia','eswatini','lesotho'].flatMap(c=>[`southern-africa/${c}/context.bin`,`southern-africa/${c}/international.bin`]),
 ...globalThis.AtlasCountries.byAdapter('europe').flatMap(c=>['context','neighbours','international'].map(f=>`europe/${c}/${f}.bin`))
];

if(import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 const {encodeGeo}=await import('../dist/geo-pack.mjs');
 const present=compactSources.filter(f=>fs.existsSync('dist/data/'+f));
 // Keep the previous compact files available to open previews until each replacement is ready.
 let before=0,after=0;const empty=[];
 // Keep permanent shared lakes and the Swiss survey frontier in every rebuild.
 await (await import('./alpine-lakes.mjs')).reconcileAlpineLakes();
 if(fs.existsSync('scripts/boundary-sources/central-europe/resolved.bin'))await (await import('./repair-central-enclaves.mjs')).repairCentralEnclaves();
 await (await import('./repair-rhine-levee.mjs')).repairRhineLevee();
 await (await import('./central-europe-frontiers.mjs')).preserveCentralEuropeanFrontiers();
 await (await import('./refresh-central-world.mjs')).refreshCentralWorld();
 await (await import('./finalize-central-water.mjs')).refreshCentralSelectionOutlines();
 await (await import('./antarctic-claims.mjs')).preserveAntarctica();
 await (await import('./build-context-coverage.mjs')).build();
 for(const file of present){
  const source=fs.readFileSync('dist/data/'+file),text=gunzipSync(source).toString('utf8');
  const data=JSON.parse(text);if(data.type==='FeatureCollection'&&!data.features.length)empty.push(file);
  const packed=gzipSync(encodeGeo(data,{source:createHash('sha256').update(text).digest('hex')}),{level:9});
  fs.mkdirSync(path.dirname('dist/data/compact/'+file),{recursive:true});const target='dist/data/compact/'+file;fs.writeFileSync(target+'.tmp',packed);fs.renameSync(target+'.tmp',target);
  before+=source.length;after+=packed.length;
  console.log(file.padEnd(44),(source.length/1024).toFixed(0).padStart(6),'KB ->',(packed.length/1024).toFixed(0).padStart(5),'KB');
 }
 fs.writeFileSync('dist/compact-files.mjs',`// Generated by scripts/build-compact.mjs: data files published with a compact copy under data/compact/.\nexport const compactFiles=${JSON.stringify(present)};\nexport const emptyGeometryFiles=${JSON.stringify(empty)};\n`);
 console.log(`Compact copies: ${present.length} files, ${(before/1048576).toFixed(2)} MB -> ${(after/1048576).toFixed(2)} MB.`);
 await import('./build-globe-overview.mjs');
}
