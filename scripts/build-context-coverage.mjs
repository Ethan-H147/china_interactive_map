import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {decodeData} from '../dist/geo-pack.mjs';

export function geometryBoxes(input){
 const boxes=[];
 const polygon=coordinates=>{
  const box=[Infinity,Infinity,-Infinity,-Infinity];
  const walk=c=>{if(typeof c[0]==='number'){box[0]=Math.min(box[0],c[0]);box[1]=Math.min(box[1],c[1]);box[2]=Math.max(box[2],c[0]);box[3]=Math.max(box[3],c[1]);}else c.forEach(walk);};
  walk(coordinates);if(Number.isFinite(box[0]))boxes.push(box);
 };
 const walk=value=>{
  if(!value||typeof value!=='object')return;
  if(value.type==='Polygon'||value.type==='LineString')polygon(value.coordinates);
  else if(value.type==='MultiPolygon'||value.type==='MultiLineString')value.coordinates.forEach(polygon);
  else if(value.type==='Point')polygon([value.coordinates]);
  else if(value.type==='MultiPoint')polygon(value.coordinates);
  else for(const item of Object.values(value))if(typeof item==='object')walk(item);
 };
 walk(input);
 // Group nearby islands without ever shrinking their containing boxes.
 const groups=new Map();
 for(const box of boxes){const key=Math.floor((box[0]+box[2])/30)+','+Math.floor((box[1]+box[3])/30),old=groups.get(key);if(old){old[0]=Math.min(old[0],box[0]);old[1]=Math.min(old[1],box[1]);old[2]=Math.max(old[2],box[2]);old[3]=Math.max(old[3],box[3]);}else groups.set(key,box);}
 return [...groups.values()].map(b=>b.map((v,i)=>(i<2?Math.floor(v*100):Math.ceil(v*100))/100));
}
const selected=name=>/(?:^|\/)(?:[^/]*(?:context|neighbours|international)[^/]*|world-land|world-country-outlines|atlas-frontiers)\.bin$/.test(name);
export function contextFiles(root='dist/data'){
 return fs.readdirSync(root,{recursive:true,withFileTypes:true}).filter(f=>f.isFile()&&!f.parentPath.split(path.sep).includes('compact')).map(f=>path.relative(root,path.join(f.parentPath,f.name)).replaceAll('\\','/')).filter(selected).sort();
}
export async function build(){
 const coverage={};
 for(const file of contextFiles()){
  const bytes=fs.readFileSync('dist/data/'+file),data=await decodeData(bytes);
  coverage[file]={sha256:createHash('sha256').update(bytes).digest('hex'),boxes:geometryBoxes(data)};
 }
 fs.writeFileSync('dist/context-coverage.mjs','// Generated by scripts/build-context-coverage.mjs from displayed context geometry.\nexport const coverage='+JSON.stringify(coverage)+';\n');
 console.log('Context coverage:',Object.keys(coverage).length,'sources,',Object.values(coverage).reduce((sum,row)=>sum+row.boxes.length,0),'conservative boxes');
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await build();
