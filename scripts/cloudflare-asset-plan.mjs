import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {configurations} from '../dist/europe.mjs';
import {load} from './geo-index.mjs';
import {publishedAssetPolicy} from './published-asset-policy.mjs';

export const assetControls=new Set(['.assetsignore','_redirects','_headers']);
export function cloudflareAssetPlan(root,version){
 assert(/^[a-f0-9]{40}$/.test(version),'Expected immutable source version');
 const {omitted}=publishedAssetPolicy(),retained=new Set(omitted),files=[];
 const absolute=rel=>path.join(root,...rel.split('/'));
 function walk(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,e.name);if(e.isDirectory())walk(file);else if(e.isFile())files.push(path.relative(root,file).split(path.sep).join('/'));else throw Error('Unexpected non-file asset: '+file);}}
 walk(root);files.sort();
 // Original DataV inputs and audit reports have runtime replacements. Retain
 // their original URL as a redirect to the same immutable GitHub source.
 for(const file of files)if(/^data\/\d{6}(?:_full)?\.json$/.test(file)||/^data\/europe\/[^/]+\/(?:frontier-report|alignment-report)\.json$/.test(file))retained.add(file);
 // Builders retain superseded chunk filenames. Current catalogues define the
 // complete active second/third-level hierarchy; older inputs stay in GitHub.
 for(const [id] of Object.entries(configurations)){
  const base='data/europe/'+id+'/',cat=load(absolute(base+'catalogue.bin'));
  const referenced=new Set([...Object.values(cat.chunks||{}),...Object.values(cat.thirdChunks||{})].flatMap(c=>[c.file,c.censusFile]).filter(Boolean));
  for(const sub of ['second','third'])if(fs.existsSync(absolute(base+sub)))for(const file of fs.readdirSync(absolute(base+sub)))if(file.endsWith('.bin')&&!referenced.has(sub+'/'+file))retained.add(base+sub+'/'+file);
 }
 const redirects=new Map(),fingerprints=new Map();
 for(const file of files){
  if(assetControls.has(file))continue;
  if(retained.has(file)){redirects.set(file,'https://raw.githubusercontent.com/Ethan-H147/china_interactive_map/'+version+'/dist/'+file);continue;}
  const bytes=fs.readFileSync(absolute(file)),key=path.extname(file)+':'+bytes.length+':'+createHash('sha256').update(bytes).digest('hex'),canonical=fingerprints.get(key);
  if(canonical){omitted.add(file);redirects.set(file,'/'+canonical);}else fingerprints.set(key,file);
 }
 for(const file of retained)omitted.add(file);
 assert(redirects.size<=2000,'Too many static Cloudflare redirects: '+redirects.size);
 const rules=[...redirects].map(([from,to])=>encodeURI('/'+from)+' '+encodeURI(to)+' 302');
 assert(rules.every(rule=>rule.length<=1000),'Cloudflare redirect exceeds 1000 characters');
 return {omitted,retained,redirects,redirectText:'# Generated by scripts/prepare-cloudflare.mjs. Preserve retained and duplicate asset URLs.\n'+rules.join('\n')+'\n'};
}
