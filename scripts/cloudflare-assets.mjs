import {assetControls} from './cloudflare-asset-plan.mjs';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

export const maxAssetBytes=25*1024*1024;
// This atlas now requires Workers Paid; Cloudflare enforces the account entitlement.
export const maxAssetFiles=100000;
export function assetIgnoreText(omitted){
 const paths=[...omitted].sort();
 for(const file of paths)assert(!file.startsWith('/')&&!file.split('/').includes('..')&&!/[\\\n\r*?!#\[\]]/.test(file),'Expected a literal asset path: '+file);
 return '# Generated by scripts/prepare-cloudflare.mjs; retained build inputs stay in GitHub.\n'+paths.map(file=>'/'+file).join('\n')+'\n';
}
export function auditCloudflareAssets(root,omitted,{maximumBytes=maxAssetBytes,maximumFiles=maxAssetFiles}={}){
 let files=0,bytes=0,excludedFiles=0,largest={file:null,bytes:0};const oversized=[];
 function walk(dir){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
  const file=path.join(dir,entry.name),rel=path.relative(root,file).split(path.sep).join('/');
  if(entry.isDirectory()){walk(file);continue;}assert(entry.isFile(),'Unexpected non-file asset: '+rel);
  if(assetControls.has(rel)||omitted.has(rel)){excludedFiles++;continue;}
  const size=fs.statSync(file).size;files++;bytes+=size;
  if(size>largest.bytes)largest={file:rel,bytes:size};if(size>maximumBytes)oversized.push({file:rel,bytes:size});
 }}walk(root);
 assert.equal(oversized.length,0,'Cloudflare assets exceed the 25 MiB per-file limit: '+JSON.stringify(oversized));
 assert(files<=maximumFiles,'Cloudflare asset count exceeds '+maximumFiles+': '+files);
 return {files,bytes,excludedFiles,largest,maximumBytes,maximumFiles};
}
