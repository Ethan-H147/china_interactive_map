import fs from 'node:fs';
import {gunzipSync,gzipSync} from 'node:zlib';
import {topology} from 'topojson-server';
import {mesh} from 'topojson-client';
import mapshaper from 'mapshaper';
import {reconcileSuzhouParkFragments,suzhouParkCorrection} from './suzhou-park.mjs';
const path='dist/data/city-districts.bin';
const dataset=JSON.parse(gunzipSync(fs.readFileSync(path)));
const local={type:'FeatureCollection',features:dataset.regions.features.filter(f=>f.properties.parentCity===320500)};
const corrected=await reconcileSuzhouParkFragments(local);
const points=JSON.parse((await mapshaper.applyCommands('-i input.json -points inner -o output.json format=geojson',{'input.json':corrected}))['output.json']);
for(let i=0;i<corrected.features.length;i++)corrected.features[i].properties.centroid=points.features[i].geometry.coordinates;
const byCode=new Map(corrected.features.map(f=>[f.properties.adcode,f]));
dataset.regions.features=dataset.regions.features.map(f=>byCode.get(f.properties.adcode)||f);
const top=topology({regions:corrected});
dataset.boundaries.features=dataset.boundaries.features.map(f=>f.properties.parentCity===320500?{...f,geometry:mesh(top,top.objects.regions,(a,b)=>a!==b)}:f);
fs.writeFileSync(path,gzipSync(JSON.stringify(dataset),{level:9}));
const sourcesPath='dist/data/city-district-sources.json',sources=JSON.parse(fs.readFileSync(sourcesPath));
sources.cities.find(c=>c.city===320500).correction=suzhouParkCorrection;
fs.writeFileSync(sourcesPath,JSON.stringify(sources,null,2));
console.log('Reconciled Suzhou park clipping remnants; retained district coverage and shared edges.');
