import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {gzipSync,gunzipSync} from 'node:zlib';
import {topology} from 'topojson-server';
import {mesh,merge} from 'topojson-client';
import {readData} from './read-data.mjs';
import {reconcileZhuhaiMacau,seamReview} from './zhuhai-macau.mjs';
import {reviewedPaths} from './reconcile-river-boundaries.mjs';
const data=readData('display-boundaries.json'),before=structuredClone(data);
const rules=JSON.parse(fs.readFileSync('scripts/additional-sources/water/boundary-reaches.json')),riverPaths=reviewedPaths(data.subdivisions,rules);
const land=JSON.parse(gunzipSync(fs.readFileSync('dist/data/pearl-coast-land.bin')));
const result=await reconcileZhuhaiMacau(data.subdivisions.features,land);
if(!result.additions.length){console.log('Gongbei seam already reconciled');process.exit(0);}
data.subdivisions.features=result.features;
assert.deepEqual(reviewedPaths(data.subdivisions,rules),riverPaths);
const top=topology({regions:data.subdivisions}),regions=top.objects.regions;
data.provinces.features.find(f=>f.properties.adcode===440000).geometry=merge(top,regions.geometries.filter(g=>g.properties.provinceCode===440000));
const pref=g=>g.properties.level==='taiwan-region'||g.properties.level==='city'&&String(g.properties.adcode).slice(2,4)!=='90',same=(a,b)=>a.properties.provinceCode===b.properties.provinceCode;
data.boundaries={province:mesh(top,regions,(a,b)=>a===b||!same(a,b)),prefecture:mesh(top,regions,(a,b)=>a!==b&&same(a,b)&&(pref(a)||pref(b))),other:mesh(top,regions,(a,b)=>a!==b&&same(a,b)&&!pref(a)&&!pref(b))};
const report={...seamReview,baseline:'436788db56fc56bce307c16688c7bd3137faf066',closedLandGaps:result.additions.length,additions:{type:'FeatureCollection',features:result.additions}};
fs.writeFileSync('artifacts/zhuhai-macau-before.json',JSON.stringify(before));
fs.writeFileSync('dist/data/zhuhai-macau-border.json',JSON.stringify(report));
const serialized=Buffer.from(JSON.stringify(data)),compressed=gzipSync(serialized,{level:9}),parts=[];
for(let offset=0,i=0;offset<compressed.length;offset+=4*1024*1024,i++){const name='display-boundaries.'+String(i).padStart(2,'0')+'.bin';parts.push(name);fs.writeFileSync('dist/data/'+name,compressed.subarray(offset,offset+4*1024*1024));}
fs.writeFileSync('dist/data/display-boundaries.parts.json',JSON.stringify({compression:'gzip',parts,compressedBytes:compressed.length,uncompressedBytes:serialized.length,sha256:createHash('sha256').update(serialized).digest('hex')},null,2));
const provenance=readData('additional-sources.json');provenance.processing.zhuhaiMacau=seamReview.method;
fs.writeFileSync('dist/data/additional-sources.json',JSON.stringify(provenance,null,2));
const riverReport=readData('river-boundary-report.json');riverReport.administrativeSha256=createHash('sha256').update(JSON.stringify(data.subdivisions)).digest('hex');
fs.writeFileSync('dist/data/river-boundary-report.json',JSON.stringify(riverReport,null,2));
console.log('Closed Gongbei land gaps:',result.additions.length);
