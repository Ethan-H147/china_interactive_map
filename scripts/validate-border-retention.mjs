import assert from 'node:assert/strict';
import {createBorderZoomPolicy} from '../dist/border-handoff.mjs';
import {createMapScene} from '../dist/map-scene.mjs';
import {testMap} from './test-map.mjs';

const zoom=createBorderZoomPolicy();
assert.deepEqual(zoom.update(3.4),{prepare:false,coarse:true});
assert.deepEqual(zoom.update(3.6),{prepare:true,coarse:true});
for(const z of [3.4,3.6,3.1,3.9])assert.deepEqual(zoom.update(z),{prepare:true,coarse:true},'Reversals retain prepared detail without prematurely drawing it');
assert.deepEqual(zoom.update(4),{prepare:true,coarse:false});
for(const z of [3.99,4.01,3.76,4.1])assert.deepEqual(zoom.update(z),{prepare:true,coarse:false},'Reversals retain the committed border representation');
assert.deepEqual(zoom.update(3.7),{prepare:true,coarse:true});
assert.deepEqual(zoom.update(2.99),{prepare:false,coarse:true},'Distant world views release detail work');
assert.deepEqual(zoom.update(8),{prepare:true,coarse:false});
assert.deepEqual(zoom.update(8,false),{prepare:false,coarse:true},'Unsupported/unready renderers reset the policy');

const map=testMap(),scene=createMapScene(map);
map.addSource('canonical',{serialize:()=>({data:'atlas-data://canonical?file=europe/france/international.bin'})});
const add=(id,owners)=>map.addLayer({id,source:id,type:'line',metadata:{atlasInternationalBorder:true,atlas:{role:'border',...(owners?{borderPreviewOwners:owners}:{})}},paint:{}});
add('chad-international');add('legacy-border');
scene.setBorderOwnership(true);
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible','An absent provider cannot suppress its fallback');
add('canonical',['chad-international','sudan-international']);
assert.equal(map.getLayoutProperty('chad-international','visibility'),'none','Covered adapter sources do not prepare duplicate tiles');
assert.equal(scene.baseVisibility('chad-international'),'visible','Ownership preserves adapter intent');
assert.equal(map.getLayoutProperty('legacy-border','visibility'),'visible','Uncovered borders remain available');
add('sudan-international');
assert.equal(map.getLayoutProperty('sudan-international','visibility'),'none','Late-loaded adapters inherit ownership before their first source update');
map.getBounds=()=>({toArray:()=>[[110,0],[120,10]]});map.emit('move');
assert.equal(map.getLayoutProperty('canonical','visibility'),'none');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible','Culling the provider restores uncovered fallback work');
map.getBounds=()=>({toArray:()=>[[-2,44],[8,50]]});map.emit('move');
assert.equal(map.getLayoutProperty('canonical','visibility'),'visible');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'none','Returning the provider suppresses duplicate preparation');
scene.setOverview(true);scene.setBorderPreparation(true);
assert.equal(map.getLayoutProperty('canonical','visibility'),'visible');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'none');
scene.setBorderPreparation(false);scene.setBorderPreparation(true);
assert.equal(map.getLayoutProperty('chad-international','visibility'),'none','Overview preparation never wakes an owned adapter copy');
scene.setOverview(false);
map.setLayoutProperty('canonical','visibility','none');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible','Intentionally hiding the provider restores fallback ownership');
map.setLayoutProperty('sudan-international','visibility','none');
map.setLayoutProperty('canonical','visibility','visible');
scene.setBorderOwnership(false);
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible');
assert.equal(map.getLayoutProperty('sudan-international','visibility'),'none','Disabling ownership preserves explicit adapter visibility');
scene.setBorderOwnership(true);scene.setSnapshot('chad');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible','Snapshot views retain their own borders');
scene.setSnapshot(null);
assert.equal(map.getLayoutProperty('chad-international','visibility'),'none');
map.removeLayer('canonical');
assert.equal(map.getLayoutProperty('chad-international','visibility'),'visible','Removing the provider restores its fallback');
assert.equal(map.getLayoutProperty('sudan-international','visibility'),'none');
console.log('Border zoom hysteresis, bounded preparation, canonical source ownership, late adapters, explicit visibility, snapshots and fallback cleanup passed.');
