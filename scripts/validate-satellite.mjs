import assert from 'node:assert/strict';
import {createSatelliteDisplay,satelliteVisible,imageryOpacity,sourceId,provinceOpacity,blendColor} from '../dist/satellite.mjs';
import {createMapScene} from '../dist/map-scene.mjs';
import {testMap} from './test-map.mjs';
assert(satelliteVisible({enabled:true,quiz:false}));assert(!satelliteVisible({enabled:true,quiz:true}));
assert.equal(imageryOpacity(150),1);assert.equal(imageryOpacity(-1),0);assert.equal(imageryOpacity('bad'),1);
assert.equal(provinceOpacity(true).at(-1),0);assert.equal(provinceOpacity(false).at(-1),1);
assert.equal(blendColor('#987343','#fff0bb',1),'#fff0bb');
const element=value=>({value,hidden:true,checked:false,textContent:'',handlers:{},addEventListener(type,fn){this.handlers[type]=fn;},fire(type){this.handlers[type]();}});
const ui={input:element(),options:element(),opacity:element('100'),output:element(),status:element()};
const map=testMap(),scene=createMapScene(map);let quiz=false,timeout,appearance=[];
map.addLayer({id:'no-country-name-required',type:'fill'});
const display=createSatelliteDisplay(map,{quiz:()=>quiz,mode:()=>'',onVisible:(...args)=>appearance.push(args),schedule:fn=>{timeout=fn;return 1;},cancel:()=>timeout=undefined},ui);
display.sync();assert.equal(Object.keys(map.getStyle().sources).length,0,'Imagery requires opt-in');
ui.input.checked=true;ui.input.fire('change');
assert.equal(scene.satellite.visible,false,'Keep atlas paint until an actual tile loads');
map.emit('error',{sourceId});assert(ui.input.checked,'One failed tile cannot disable the whole service');
map.emit('sourcedata',{sourceId,sourceDataType:'metadata'});assert(!scene.satellite.visible);
map.emit('sourcedata',{sourceId,tile:{state:'loaded'}});assert(scene.satellite.visible);assert.equal(timeout,undefined);
map.addLayer({id:'a-future-country-added-after-imagery',type:'fill'});
assert.equal(map.getPaintProperty('a-future-country-added-after-imagery','fill-opacity')[1][2],0,'Late layers follow the same state without another sync call');
ui.opacity.value='40';ui.opacity.fire('input');assert.equal(map.getPaintProperty(sourceId,'raster-opacity'),.4);assert.equal(ui.output.textContent,'40%');
quiz=true;display.sync();assert.equal(map.getLayoutProperty(sourceId,'visibility'),'none');assert(!scene.satellite.visible);assert(ui.input.checked);
quiz=false;display.sync();assert(scene.satellite.visible);
ui.input.checked=false;ui.input.fire('change');assert.equal(map.getPaintProperty('no-country-name-required','fill-opacity'),1);
assert.equal(appearance.at(-1)[0],false);
map.removeLayer(sourceId);map.removeSource(sourceId);
const ui2={input:element(),options:element(),opacity:element('100'),output:element(),status:element()};
createSatelliteDisplay(map,{quiz:()=>false,schedule:fn=>{timeout=fn;return 1;},cancel:()=>timeout=undefined},ui2);
ui2.input.checked=true;ui2.input.fire('change');timeout();
assert(!ui2.input.checked);assert(!map.getSource(sourceId));assert.match(ui2.status.textContent,/retry/);
ui2.input.checked=true;ui2.input.fire('change');assert(map.getSource(sourceId));assert.equal(scene.satellite.visible,false);
map.emit('sourcedata',{sourceId,tile:{state:'loaded'}});assert(scene.satellite.visible);
console.log('Satellite lifecycle: opt-in, tile readiness, late layers, opacity, quiz suspension, restoration, service failure and retry passed.');
