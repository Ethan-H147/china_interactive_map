import assert from 'node:assert/strict';
import {createMapScene} from '../dist/map-scene.mjs';
import {testMap} from './test-map.mjs';
const map=testMap(),states=new Map();let draws=0;
map.painter={renderLayer(){draws++;}};
map.setFeatureState=(target,patch)=>states.set(target.id,{...states.get(target.id),...patch});
map.setFilter=(id,filter)=>map.getLayer(id).filter=filter;
map.getFilter=id=>map.getLayer(id)?.filter;
createMapScene(map,{version:'6.11.2'});
map.addSource('regions',{type:'geojson',promoteId:'id'});
const id='regions-selection-fill';
map.addLayer({id,source:'regions',type:'fill',metadata:{atlas:{stableSelectionFill:true}},layout:{visibility:'visible'},filter:['==',['get','id'],''],paint:{'fill-color':'#123456'}});
const draw=()=>map.painter.renderLayer(null,null,map.getLayer(id),[],{});
draw();assert.equal(draws,0,'Empty highlight skips native drawing while its buckets stay resident');
assert.equal(map.getLayoutProperty(id,'visibility'),'visible');
map.setFilter(id,['==',['get','id'],'A']);draw();assert.equal(draws,1);
assert.equal(map.getLayoutProperty(id,'visibility'),'visible');
assert.equal(states.get('A')['_atlasSelection:'+id],true);
map.setFilter(id,['==',['get','id'],'B']);draw();assert.equal(draws,2);
assert.equal(states.get('A')['_atlasSelection:'+id],false);assert.equal(states.get('B')['_atlasSelection:'+id],true);
map.setFilter(id,['==',['get','id'],'']);draw();assert.equal(draws,2,'Clearing selection skips drawing again');
assert.equal(map.getLayoutProperty(id,'visibility'),'visible');
console.log('Stable selection fills: resident layout, state-only highlights, previous-selection clearing and empty GPU-draw skipping passed.');
