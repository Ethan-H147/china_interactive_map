import fs from 'node:fs';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {gunzipSync} from 'node:zlib';
import {readData} from './read-data.mjs';
import {reconcileZhuhaiMacau} from './zhuhai-macau.mjs';
import {run,area,collection} from './pearl-coast.mjs';
const report=readData('zhuhai-macau-border.json');
const show=name=>{const r=spawnSync('git',['-c','safe.directory='+process.cwd().replaceAll('\\','/'),'show',report.baseline+':dist/data/'+name],{maxBuffer:60e6});assert.equal(r.status,0);return r.stdout;};
const m=JSON.parse(show('display-boundaries.parts.json')),before=JSON.parse(gunzipSync(Buffer.concat(m.parts.map(show)))),after=readData('display-boundaries.json');
for(const f of before.subdivisions.features)if(f.properties.adcode!==440400)assert.deepEqual(after.subdivisions.features.find(g=>g.properties.adcode===f.properties.adcode),f,'Unrelated subdivision changed');
for(const f of before.provinces.features)if(f.properties.adcode!==440000)assert.deepEqual(after.provinces.features.find(g=>g.properties.adcode===f.properties.adcode),f,'Unrelated province changed');
const old=before.subdivisions.features.find(f=>f.properties.adcode===440400),city=after.subdivisions.features.find(f=>f.properties.adcode===440400);
assert.deepEqual(city.properties,old.properties);
const total=fc=>fc.features.reduce((s,f)=>s+(f.geometry?area(f.geometry):0),0);
assert(total(await run('-i old.json -erase new.json',{'old.json':old,'new.json':city}))<1e-12,'Existing Zhuhai land lost');
const added=await run('-i new.json -erase old.json',{'new.json':city,'old.json':old});
assert(Math.abs(area(city.geometry)-area(old.geometry)-total(report.additions))<1e-12,'Area change differs from the reviewed gaps');
const polygons=g=>g.type==='Polygon'?[g.coordinates]:g.coordinates;
const outside=g=>polygons(g).filter(p=>p[0].every(([x,y])=>x<113.54||x>113.557||y<22.212||y>22.221));
assert.deepEqual(outside(city.geometry),outside(old.geometry),'Remote island or coastal component changed');
const land=JSON.parse(gunzipSync(fs.readFileSync('dist/data/pearl-coast-land.bin')));
assert(total(await run('-i gaps.json -erase land.json',{'gaps.json':report.additions,'land.json':land}))<1e-12,'Sea filled by repair');
const macau=collection(after.subdivisions.features.filter(f=>f.properties.provinceCode===820000));
assert(total(await run('-i city.json -clip macau.json',{'city.json':city,'macau.json':macau}))<1e-12,'New Macau overlap');
assert.equal((await reconcileZhuhaiMacau(after.subdivisions.features,land)).additions.length,0,'Correction is not stable');
assert.equal(report.closedLandGaps,3);
console.log('Zhuhai–Macau: three terrestrial gaps closed; Macau, other cities, islands and original Zhuhai land preserved; no sea fill or overlap.');
